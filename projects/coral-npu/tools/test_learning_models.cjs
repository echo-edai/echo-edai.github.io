// Behavioral checks for the browser's teaching models; not upstream RTL proof.
const assert=require('node:assert/strict');
const M=require('../logic-models.js');
let checks=0;
function check(value,message){checks++;assert.ok(value,message);}
let f=M.fifoInitial();
for(let i=1;i<=4;i++)f=M.fifoStep(f,{valid:true,ready:false,data:i}).state;
check(f.queue.join()==='1,2,3,4','FIFO fill order');
let r=M.fifoStep(f,{valid:true,ready:true,data:9});f=r.state;
check(!r.signals.push&&r.signals.pop&&f.queue.join()==='2,3,4','Full-old-state conservative refill policy');
f=M.fifoStep(f,{valid:true,ready:true,data:9}).state;
check(f.queue.join()==='3,4,9','simultaneous push/pop');
let s=M.scoreboardInitial();
s=M.scoreboardStep(s,{valid:true,resource:true,source:0,destination:8}).state;
check(s.busy===8,'allocate');
r=M.scoreboardStep(s,{valid:true,resource:true,source:8,destination:16});
check(!r.signals.accepted&&r.signals.raw&&r.state.busy===8,'RAW prevents issue');
r=M.scoreboardStep(s,{valid:true,resource:true,source:0,destination:8});
check(!r.signals.accepted&&r.signals.waw,'WAW prevents issue');
s=M.scoreboardStep(s,{valid:false,resource:true,source:0,destination:0,wb:8}).state;
check(s.busy===0,'writeback release');
s=M.scoreboardStep(s,{valid:true,resource:true,source:0,destination:16,wb:16}).state;
check(s.busy===16,'allocation wins clear');
let d=M.directoryInitial();
const step=input=>{r=M.directoryStep(d,input);d=r.state;
  if(d.permission==='M')check(d.sharers===(1<<d.owner),'M has one owner');
  if(d.permission==='I')check(d.sharers===0,'I has no sharers');
  return r;};
step({reqValid:true,core:0});check(d.phase==='RESP'&&d.sharers===1,'first reader');
step({reqValid:true,core:1,write:true});check(d.pendingCore===0&&d.sharers===1,'response stall blocks overwrite');
step({respReady:true});step({reqValid:true,core:1});check(d.permission==='S'&&d.sharers===3,'shared readers');
step({respReady:true});step({reqValid:true,core:0,write:true});
check(d.phase==='PROBE'&&d.target===1&&d.permission==='S','writer requires invalidation');
step({});check(d.phase==='PROBE','probe backpressure');
step({probeReady:true});step({ackValid:true,ackCore:0});check(d.phase==='WAIT_ACK','wrong ACK cannot grant');
step({ackValid:true,ackCore:1});check(d.phase==='RESP'&&d.permission==='M'&&d.owner===0,'correct ACK grants M');
step({respReady:true});step({reqValid:true,core:1});check(d.phase==='PROBE'&&!d.pendingWrite&&d.target===0,'remote read requires owner downgrade');
step({probeReady:true});step({ackValid:true,ackCore:0});check(d.permission==='S'&&d.sharers===3,'downgrade creates sharing');
step({reset:true});check(d.phase==='IDLE'&&d.permission==='I','reset controller');
console.log(`PASS: ${checks} browser-model checks`);
